"""Many-treatments-vs-ONE-control tests: b-a, c-a, d-a.

WHY THIS FILE EXISTS (Q, 2026-09-11): the objective of the study is "does the
proposed method improve on the baseline", so the family of hypotheses is the
THREE vs-control contrasts, not all six pairwise comparisons. Correcting c-a
against comparisons like d-b that were never of interest is over-penalising.
omnibus_tests.py uses the 6-pair family and is the right tool for "do the four
models differ at all"; this file is the right tool for the study's actual
question.

CLAUDE.md pre-specified INCART 3-class as the headline cross-dataset metric on
2026-08-11, long before these runs existed, so treating it as the PRIMARY
endpoint is pre-specification and not post-hoc selection.

Three corrections are reported, from most to least conservative:

  1. BONFERRONI / HOLM over the 3 contrasts. Simple, valid, but assumes the
     contrasts are independent. They are NOT - all three share arm a, so they
     are positively correlated, and Holm is therefore conservative here.

  2. MAX-T PERMUTATION (the honest one). For paired data the exact null is
     generated by flipping the sign of each seed's difference vector. With n=10
     that is 2^10 = 1024 sign patterns, so this is EXHAUSTIVE, not sampled.
     Flipping signs for all three contrasts together preserves their
     correlation, so the max-|t| null automatically accounts for the shared
     control. This is the paired analogue of Dunnett's test.

  3. UNCORRECTED, for a single pre-specified primary endpoint. Defensible only
     if exactly one endpoint is declared primary in advance.

Run: python code/vs_baseline_tests.py [--protocol inter_patient]
"""
import argparse
import csv
import itertools
import json
import os
import sys

import numpy as np
from scipy import stats

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from four_model_ttests import PROTOCOLS, SUBSETS  # noqa: E402


def holm(pvals):
    p = np.asarray(pvals, float)
    m = len(p)
    order = np.argsort(p)
    adj = np.empty(m)
    running = 0.0
    for rank, idx in enumerate(order):
        running = max(running, (m - rank) * p[idx])
        adj[idx] = min(running, 1.0)
    return adj


def paired_t(d):
    """t statistic of a paired difference vector."""
    sd = d.std(ddof=1)
    if sd == 0:
        return np.inf if d.mean() != 0 else 0.0
    return d.mean() / (sd / np.sqrt(len(d)))


def maxt_permutation(D):
    """Exact max-|t| sign-flip permutation p-values.

    D is (n_seeds x n_contrasts). Returns adjusted p per contrast.
    Flipping a seed's sign flips it in EVERY contrast simultaneously, which is
    what preserves the correlation induced by the shared control arm.
    """
    n, m = D.shape
    obs = np.array([abs(paired_t(D[:, j])) for j in range(m)])
    if n > 22:                       # 2^22 ~ 4M; beyond that sample instead
        rng = np.random.default_rng(0)
        signs = rng.choice([-1.0, 1.0], size=(200_000, n))
    else:
        signs = np.array(list(itertools.product([-1.0, 1.0], repeat=n)))
    maxt = np.empty(len(signs))
    for i, s in enumerate(signs):
        Ds = D * s[:, None]
        maxt[i] = max(abs(paired_t(Ds[:, j])) for j in range(m))
    # adjusted p = P(max|t| under null >= observed |t|)
    return np.array([(maxt >= o).mean() for o in obs]), obs, len(signs)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--protocol", choices=sorted(PROTOCOLS), default="inter_patient")
    ap.add_argument("--primary", default="INCART 3-class",
                    help="Pre-specified primary endpoint (dataset + subset).")
    args = ap.parse_args()
    cfg = PROTOCOLS[args.protocol]
    seeds = cfg["seeds"]
    tags = {a[0]: a[2] for a in cfg["arms"]}

    datasets = ([("INCARTval", "mitbih_val"), ("MITtarget", "incart")]
                if args.protocol == "reverse"
                else [("MIT", "mitbih_val"), ("INCART", "incart")])

    def series(arm, block, k):
        out = []
        for s in seeds:
            m = json.load(open(f"runs/{tags[arm]}_seed{s}/metrics.json"))
            f = np.asarray(m[block]["macro_checkpoint"]["per_class_f1"], float)
            out.append(f[:k].mean())
        return np.asarray(out)

    print("=" * 96)
    print(f"VS-BASELINE CONTRASTS  |  {cfg['label']}  |  n={len(seeds)} seeds")
    print("=" * 96)
    print("Family = {b-a, c-a, d-a}: the study's actual question.\n")

    rows = []
    for dname, block in datasets:
        for sname, k in SUBSETS:
            A = series("a", block, k)
            D = np.column_stack([series(x, block, k) - A for x in ("b", "c", "d")])
            praw = [2 * (1 - stats.t.cdf(abs(paired_t(D[:, j])), len(seeds) - 1))
                    for j in range(3)]
            ph = holm(praw)
            pm, tobs, nperm = maxt_permutation(D)

            star = "  <== PRIMARY ENDPOINT" if f"{dname} {sname}" == args.primary else ""
            print(f"{dname} {sname}{star}")
            print(f"  {'contrast':<10}{'effect':>10}{'t':>8}{'p raw':>9}"
                  f"{'p Holm(3)':>11}{'p maxT':>9}{'wins':>7}")
            for j, name in enumerate(("b - a", "c - a", "d - a")):
                w = int((D[:, j] > 0).sum())
                mark = ""
                if pm[j] < 0.05:
                    mark = "  *"
                elif pm[j] < 0.10:
                    mark = "  ."
                print(f"  {name:<10}{D[:, j].mean():>+10.4f}{tobs[j]:>8.2f}"
                      f"{praw[j]:>9.4f}{ph[j]:>11.4f}{pm[j]:>9.4f}"
                      f"{w:>5}/{len(seeds)}{mark}")
                rows.append(dict(dataset=dname, subset=sname, contrast=name,
                                 effect=round(float(D[:, j].mean()), 4),
                                 t=round(float(tobs[j]), 3),
                                 p_raw=round(float(praw[j]), 4),
                                 p_holm3=round(float(ph[j]), 4),
                                 p_maxt=round(float(pm[j]), 4),
                                 wins=f"{w}/{len(seeds)}"))
            print()

    print(f"(max-T null built from {nperm} exhaustive sign flips; "
          f"* p<0.05, . p<0.10)")
    os.makedirs("runs/_analysis", exist_ok=True)
    path = f"runs/_analysis/{cfg['out']}_vs_baseline.csv"
    with open(path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        w.writeheader(); w.writerows(rows)
    print(f"wrote {path}  ({len(rows)} rows)")


if __name__ == "__main__":
    main()
